# The home page's head
# --------------------------------------------------------------------------- #
def home_description(f: HomeFacts) -> str:
    return (
        f"Porchlamp ranks {fmt_int(f.total)} open-source projects by whether they reply, review or merge a stranger's pull "
        "request, not by stars. Find the projects that leave the light on."
    )


def home_jsonld(f: HomeFacts, title: str) -> dict:
    """The home's structured data: the creator, the site (no search action: ``/?q=`` needs JavaScript to answer), the
    page (about the report's Dataset) and the top ranked projects, each at its own page."""
    return {
        "@context": "https://schema.org",
        "@graph": [
            {"@type": "Person", "@id": CREATOR_ID, "name": "Rahul Kumar", "alternateName": "pctablet505", "url": "https://github.com/pctablet505"},
            {
                "@type": "WebSite", "@id": f"{SITE}/#website", "url": f"{SITE}/", "name": "Porchlamp",
                "alternateName": ["Porchlamp rankings"],
                "description": (
                    "Open-source projects ranked by what happens to a stranger's pull request, not by stars. "
                    f"{fmt_int(f.total)} repositories evaluated across {_parameter_count(f)} parameters, {len(f.pillars)} pillars, "
                    f"and {f.personas} contributor personas."
                ),
                "inLanguage": "en", "creator": {"@id": CREATOR_ID},
            },
            {
                "@type": "WebPage", "@id": f"{SITE}/#webpage", "url": f"{SITE}/", "name": title,
                "description": (
                    "A porch lamp left on tells a visitor they are expected. Porchlamp ranks "
                    f"{fmt_int(f.total)} open-source projects by what happens to a stranger's pull request, not by stars."
                ),
                "isPartOf": {"@id": f"{SITE}/#website"}, "about": {"@id": f"{f.report_latest}#dataset"},
                "inLanguage": "en", "dateModified": f.as_of,
            },
            {
                "@type": "ItemList", "@id": f"{SITE}/#top-repositories",
                "name": f"Top {TOP_LISTED} open-source projects by Porchlamp score (balanced lens, snapshot {f.snapshot_id})",
                "numberOfItems": len(f.rows[:TOP_LISTED]), "itemListOrder": "https://schema.org/ItemListOrderDescending",
                "itemListElement": [
                    {
                        "@type": "ListItem", "position": i,
                        "name": f"{r.owner}/{r.name} ({r.ecosystem}) — Porchlamp {r.score}, Tier {r.tier}, {r.quadrant}",
                        "url": project_url(r.owner, r.name),
                    }
                    for i, r in enumerate(f.rows[:TOP_LISTED], 1)
                ],
            },
        ],
    }


def home_page(template: str, f: HomeFacts) -> str:
    """``web/app/index.html`` with this snapshot's description and structured data; ``web/prerender.mjs`` then draws the
    header, nav, footer and the ranked view (the findings line and the first page of rows) into it."""
    found = re.findall(r'<meta name="description" content="[^"]*">', template)
    titles = re.findall(r"<title>([^<]*)</title>", template)
    if len(found) != 1 or len(titles) != 1:
        raise ReportError("web/app/index.html has no single description and title to build the home from")
    page = template.replace(found[0], f'<meta name="description" content="{_a(home_description(f))}">')
    return _with_ld(page, home_jsonld(f, titles[0]))


# --------------------------------------------------------------------------- #
# llms.txt
# --------------------------------------------------------------------------- #
def _row_line(r: Row) -> str:
    return (f"{r.rank}. `{r.owner}/{r.name}` ({r.ecosystem}) — Score `{r.score}` · Coverage `{r.coverage}` · "
            f"Tier `{r.tier}` · `{r.quadrant}`")


def llms_txt(f: HomeFacts) -> str:
    """The site's summary for language models: the findings, the pages that read without JavaScript, the pillars and
    parameters, the top projects and the data files. Every number is the snapshot's."""
    sid, top = f.snapshot_id, f.rows[0]
    persona_names = copy_js_map("PERSONA_NAMES")
    lines = [
        f"# Porchlamp ({SITE}/)",
        "",
        "> A porch lamp left on tells a visitor they are expected. Porchlamp ranks "
        f"{fmt_int(f.total)} open-source projects by what happens to a stranger's pull request, not by how many stars the "
        "project has. Every score traces back to recorded GitHub responses and SHA-256 content hashes (by Rahul Kumar, "
        "`pctablet505`).",
        "",
        f"## Findings (snapshot `{sid}`)",
        *(f"- **{lead}** {text}" for lead, text in f.findings),
        f"- {f.corpus}",
        f"- {fmt_int(f.ranked)} projects are ranked under the balanced lens; {fmt_int(f.gated)} are gated and "
        f"{fmt_int(f.unrated)} unrated, each listed with its reason under [Not ranked]({SITE}/not-ranked/).",
        "",
        "## Static pages (readable without JavaScript)",
        f"- [{CITE_TITLE} (latest snapshot)]({f.report_latest})",
        f"- [The same report, frozen for citation (snapshot `{sid}`)]({f.report_frozen})",
        f"- [CSV of the {fmt_int(f.ranked)} ranked projects (CC BY 4.0)]({f.report_csv})",
        f"- [Methodology: every gate, pillar, lens, weight and parameter]({SITE}/methodology/)",
        "",
        "## One page per ranked project (readable without JavaScript)",
        f"To check a project, open {SITE}/projects/<owner>/<name>/ (lower case).",
        "Each page opens with the project's median time to a first human reply to an outside pull request, the share that "
        f"got no reply within {f.deadline_days} days, and its rank overall and for first-time contributors. Example: "
        f"[{top.owner}/{top.name}]({project_url(top.owner, top.name)})",
        "",
        "## Ecosystem and lens pages (readable without JavaScript)",
        f"Each page lists the top {f.preset_rows} projects of its cut, with score and tier, and each name opens that project's page.",
        *(f"- [{name} projects that answer outside pull requests]({SITE}{path})" for _code, path, name in f.ecosystem_pages),
        *(f"- [Open-source projects for {phrase}]({SITE}{path})" for _code, path, phrase in f.lens_pages),
        "",
        f"## {len(f.pillars)} pillars and {_parameter_count(f)} parameters (balanced weights)",
        *(f"{i}. **{name} ({weight}%):** {', '.join(params)}." for i, (name, weight, params) in enumerate(f.pillars, 1)),
        "",
        f"## Top {len(f.rows)} ranked projects (balanced lens, snapshot `{sid}`)",
        *(_row_line(r) for r in f.rows),
        "",
        "## Data files",
        f"- [Snapshot provenance and hashes]({SITE}/data/{sid}/snapshot.json)",
        *(f"- [{persona_names[lens]} leaderboard (JSON)]({SITE}/data/{sid}/leaderboard-{lens}.json)" for lens in persona_names),
        f"- [Leverage and friction matrix (JSON)]({SITE}/data/{sid}/matrix.json)",
        f"- [Methodology (JSON)]({SITE}/data/{sid}/methodology.json)",
        f"- [Report (JSON)]({SITE}/data/{sid}/report.json)",
        f"- [Atom feed]({SITE}/feed.xml)",
        f"- [Sitemap index]({SITE}/sitemap.xml): [pages]({SITE}/sitemap-pages.xml) and [projects]({SITE}/sitemap-projects.xml)",
    ]
    return "\n".join(lines) + "\n"


# --------------------------------------------------------------------------- #
# feed.xml
# --------------------------------------------------------------------------- #
def _entry(title: str, link: str, entry_id: str, updated: str, summary: str) -> str:
    return (
        "  <entry>\n"
        f"    <title>{escape(title, quote=False)}</title>\n"
        f'    <link href="{escape(link)}" rel="alternate" />\n'
        f"    <id>{escape(entry_id, quote=False)}</id>\n"
        f"    <updated>{updated}</updated>\n"
        f"    <summary>{escape(summary, quote=False)}</summary>\n"
        "  </entry>\n"
    )


def feed_xml(f: HomeFacts) -> str:
    """The Atom feed: the snapshot, the report, two lens pages and the methodology, each entry at its page's address."""
    updated, sid = f"{f.as_of}T00:00:00Z", f.snapshot_id
    entries = [
        _entry(f"Porchlamp snapshot {sid}: {fmt_int(f.total)} open-source projects measured", f"{SITE}/", f"{SITE}/#snapshot-{sid}", updated,
               f"{f.corpus} {fmt_int(f.ranked)} ranked, {fmt_int(f.gated)} gated and {fmt_int(f.unrated)} unrated."),
        _entry(CITE_TITLE, f.report_latest, f"{f.report_latest}#snapshot-{sid}", updated,
               " ".join(f"{lead} {text}" for lead, text in f.findings[:2])),
    ]
    for code, path, phrase in f.lens_pages:
        if code in ("first_timer", "ai_assisted"):
            url = f"{SITE}{path}"
            entries.append(_entry(
                f"Open-source projects for {phrase} ({fmt_int(f.lens_totals[code])} ranked)", url, f"{url}#snapshot-{sid}", updated,
                f"This view ranks {fmt_int(f.lens_totals[code])} projects for {phrase}. It weighs {f.lens_weights[code]}.",
            ))
    entries.append(_entry(
        f"Porchlamp methodology: {len(f.pillars)} pillars, {_parameter_count(f)} parameters, gates and hashes",
        f"{SITE}/methodology/", f"{SITE}/methodology/#snapshot-{sid}", updated,
        f"Every gate, pillar, lens, weight and parameter, with the constants hash {f.constants_hash}.",
    ))
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<feed xmlns="http://www.w3.org/2005/Atom">\n'
        "  <title>Porchlamp — Find the projects that leave the light on</title>\n"
        "  <subtitle>Open-source projects ranked by what happens to a stranger's pull request, not by stars.</subtitle>\n"
        f'  <link href="{SITE}/feed.xml" rel="self" type="application/atom+xml" />\n'
        f'  <link href="{SITE}/" rel="alternate" type="text/html" />\n'
        f"  <id>{SITE}/</id>\n"
        f"  <updated>{updated}</updated>\n"
        f"  <logo>{SITE}/og.png</logo>\n"
        f"  <icon>{SITE}/favicon.svg</icon>\n"
        "  <author>\n"
        "    <name>Rahul Kumar (pctablet505)</name>\n"
        "    <uri>https://github.com/pctablet505</uri>\n"
        "  </author>\n"
        + "".join(entries)
        + "</feed>\n"
    )
